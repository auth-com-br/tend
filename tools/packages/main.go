// Command packages writes what package managers install a release from:
// a Homebrew formula (dist/tend.rb), for a tap, and a Nix expression
// (dist/tend.nix), for a flake or an overlay — both from `make dist`'s
// checksums, so they point at the release's own binaries (#49).
//
//	go run ./tools/packages -version v0.18.0 -dir dist
//
// The checksums are read from the published release, not from dist/: a
// dist/ rebuilt since — or left from the release before, as the one this
// was written beside was — has other hashes than the files brew and nix
// will download, and a package built from it fails to install. -local
// reads dist/SHA256SUMS instead, for a release not yet published.
//
// The binaries are the release's, not built again: they are what tend
// update installs and what latest.json vouches for, and a package that
// built from source would be a second tend to keep honest.
package main

import (
	"bufio"
	"encoding/base64"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/auth-com-br/tend/internal/update"
)

func main() {
	version := flag.String("version", "", "the release's tag, v0.18.0")
	dir := flag.String("dir", "dist", "where SHA256SUMS is, and where tend.rb and tend.nix go")
	repo := flag.String("repo", "auth-com-br/tend", "the GitHub repository the release is in")
	local := flag.Bool("local", false, "read dist/SHA256SUMS rather than the published release's")
	flag.Parse()
	if err := run(*version, *dir, *repo, *local); err != nil {
		fmt.Fprintln(os.Stderr, "packages:", err)
		os.Exit(1)
	}
}

// platforms are the four `make dist` builds, as each manager names them.
var platforms = []struct{ file, brewOS, brewCPU, nixSystem string }{
	{"tend-darwin-arm64", "macos", "arm", "aarch64-darwin"},
	{"tend-darwin-amd64", "macos", "intel", "x86_64-darwin"},
	{"tend-linux-arm64", "linux", "arm", "aarch64-linux"},
	{"tend-linux-amd64", "linux", "intel", "x86_64-linux"},
}

func run(version, dir, repo string, local bool) error {
	if _, ok := update.ParseVersion(version); !ok {
		return fmt.Errorf("-version %q is not a release version (v1.2.3)", version)
	}
	base := "https://github.com/" + repo + "/releases/download/" + version
	var raw []byte
	var err error
	if local {
		raw, err = os.ReadFile(filepath.Join(dir, "SHA256SUMS"))
	} else {
		raw, err = published(base + "/SHA256SUMS")
	}
	if err != nil {
		return err
	}
	sums, err := readSums(string(raw))
	if err != nil {
		return err
	}
	for _, p := range platforms {
		if sums[p.file] == "" {
			return fmt.Errorf("SHA256SUMS has no %s: run make dist on the release's tag", p.file)
		}
	}
	formula := Formula(version, base, sums)
	expr, err := Nix(version, base, sums)
	if err != nil {
		return err
	}
	for name, text := range map[string]string{"tend.rb": formula, "tend.nix": expr} {
		out := filepath.Join(dir, name)
		if err := os.WriteFile(out, []byte(text), 0o644); err != nil {
			return err
		}
		fmt.Println(out)
	}
	return nil
}

// published fetches the release's own SHA256SUMS.
func published(url string) ([]byte, error) {
	client := &http.Client{Timeout: 30 * time.Second}
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s (is the release published? -local reads dist/)", url, resp.Status)
	}
	return io.ReadAll(io.LimitReader(resp.Body, 1<<20))
}

// readSums reads sha256sum's lines: the hash, two spaces, the file.
func readSums(text string) (map[string]string, error) {
	out := map[string]string{}
	sc := bufio.NewScanner(strings.NewReader(text))
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		if len(fields) != 2 {
			continue
		}
		if _, err := hex.DecodeString(fields[0]); err != nil || len(fields[0]) != 64 {
			return nil, fmt.Errorf("SHA256SUMS: %q is not a sha256", fields[0])
		}
		out[strings.TrimPrefix(fields[1], "*")] = fields[0]
	}
	return out, sc.Err()
}

// Formula is the Homebrew formula for a release: the binary for the
// machine, installed as bin/tend. Its test is `tend version`, which needs
// no session.
func Formula(version, base string, sums map[string]string) string {
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by tools/packages for %s; do not edit by hand.
class Tend < Formula
  desc "Terminal runtime for AI coding agents"
  homepage "https://tend.auth.com.br"
  version "%s"
  license "Apache-2.0"
`, version, strings.TrimPrefix(version, "v"))
	for _, system := range []string{"macos", "linux"} {
		fmt.Fprintf(&b, "\n  on_%s do\n", system)
		for _, p := range platforms {
			if p.brewOS != system {
				continue
			}
			fmt.Fprintf(&b, "    on_%s do\n      url \"%s/%s\"\n      sha256 \"%s\"\n    end\n", p.brewCPU, base, p.file, sums[p.file])
		}
		b.WriteString("  end\n")
	}
	b.WriteString(`
  def install
    bin.install Dir["tend-*"].first => "tend"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/tend version")
  end
end
`)
	return b.String()
}

// Nix is a Nix expression for a release, callPackage-able: the binary for
// the system, fetched by its hash. Nix wants the hash in SRI form,
// sha256-<base64>.
func Nix(version, base string, sums map[string]string) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by tools/packages for %s; do not edit by hand.
{ lib, stdenvNoCC, fetchurl }:

let
  version = "%s";
  sources = {
`, version, strings.TrimPrefix(version, "v"))
	for _, p := range platforms {
		raw, err := hex.DecodeString(sums[p.file])
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "    %s = { url = \"%s/%s\"; hash = \"sha256-%s\"; };\n",
			p.nixSystem, base, p.file, base64.StdEncoding.EncodeToString(raw))
	}
	b.WriteString(`  };
  source = sources.${stdenvNoCC.hostPlatform.system}
    or (throw "tend has no release build for ${stdenvNoCC.hostPlatform.system}");
in
stdenvNoCC.mkDerivation {
  pname = "tend";
  inherit version;
  src = fetchurl source;
  dontUnpack = true;
  installPhase = ''
    runHook preInstall
    install -Dm755 $src $out/bin/tend
    runHook postInstall
  '';
  meta = {
    description = "Terminal runtime for AI coding agents";
    homepage = "https://tend.auth.com.br";
    license = lib.licenses.asl20;
    platforms = builtins.attrNames sources;
    mainProgram = "tend";
    sourceProvenance = [ lib.sourceTypes.binaryNativeCode ];
  };
}
`)
	return b.String(), nil
}
