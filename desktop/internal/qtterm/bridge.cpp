#include "bridge.h"

#include <QClipboard>
#include <QGuiApplication>
#include <QJsonDocument>
#include <QtQml/qqml.h>

#include "_cgo_export.h"
#include "terminal.h"
#include "terminalitem.h"

static TendBridge *g_bridge = nullptr;

TendBridge::TendBridge(QObject *parent) : QObject(parent) {}

qreal TendBridge::cellWidth() const { return TerminalItem::defaultCellSize().width(); }
qreal TendBridge::cellHeight() const { return TerminalItem::defaultCellSize().height(); }

void TendBridge::setState(const QString &state) {
	if (state == m_state)
		return;
	m_state = state;
	emit stateChanged();
}

void TendBridge::setStatus(const QString &status) {
	if (status == m_status)
		return;
	m_status = status;
	emit statusChanged();
}

void TendBridge::call(const QString &method, const QVariantMap &args) {
	QByteArray m = method.toUtf8();
	QByteArray a = QJsonDocument::fromVariant(args).toJson(QJsonDocument::Compact);
	goBridgeCall(m.data(), int(m.size()), a.data(), int(a.size()));
}

extern "C" void tend_bridge_register(void) {
	if (!g_bridge)
		g_bridge = new TendBridge();
	qmlRegisterSingletonInstance("Tend", 1, 0, "Bridge", g_bridge);
}

extern "C" void tend_bridge_set_start_url(const char *url, int len) {
	if (!g_bridge)
		g_bridge = new TendBridge();
	g_bridge->setStartUrl(QString::fromUtf8(url, len));
}

extern "C" void tend_bridge_set_state(const char *json, int len) {
	if (g_bridge)
		g_bridge->setState(QString::fromUtf8(json, len));
}

extern "C" void tend_bridge_set_status(const char *text, int len) {
	if (g_bridge)
		g_bridge->setStatus(QString::fromUtf8(text, len));
}

extern "C" void tend_bridge_browser_command(const char *action, const char *url, int on) {
	if (g_bridge)
		g_bridge->sendBrowserCommand(QString::fromUtf8(action), QString::fromUtf8(url), on != 0);
}

extern "C" void tend_set_clipboard(const char *text, int len) {
	QString s = QString::fromUtf8(text, len);
	QClipboard *cb = QGuiApplication::clipboard();
	cb->setText(s, QClipboard::Clipboard);
	if (cb->supportsSelection())
		cb->setText(s, QClipboard::Selection);
}

